import { 
  CloudFormationClient, 
  DescribeStacksCommand 
} from '@aws-sdk/client-cloudformation';
import { 
  CognitoIdentityProviderClient, 
  ListUserPoolsCommand,
  ListUserPoolClientsCommand 
} from '@aws-sdk/client-cognito-identity-provider';
import { 
  ApiGatewayV2Client, 
  GetApisCommand 
} from '@aws-sdk/client-apigatewayv2';
import { S3Client, ListBucketsCommand } from '@aws-sdk/client-s3';
import { writeFileSync } from 'fs';
import { join } from 'path';

const region = process.env.AWS_REGION || 'us-east-1';

async function fetchAWSResources() {
  console.log('🔍 Fetching AWS resources for QuickChat...\n');

  const config = {};

  try {
    // 1. Get CloudFormation Stack Outputs
    console.log('[1/5] Fetching CloudFormation stack outputs...');
    const cfClient = new CloudFormationClient({ region });
    const stackResponse = await cfClient.send(
      new DescribeStacksCommand({ StackName: 'quickchat-backend' })
    );
    
    const outputs = stackResponse.Stacks[0].Outputs;
    outputs.forEach(output => {
      if (output.OutputKey === 'WebSocketUrl') {
        config.VITE_WEBSOCKET_URL = output.OutputValue;
      } else if (output.OutputKey === 'RestApiUrl') {
        config.VITE_API_URL = output.OutputValue;
      } else if (output.OutputKey === 'AttachmentsBucketName') {
        config.VITE_ATTACHMENTS_BUCKET = output.OutputValue;
      }
    });
    console.log('✅ Stack outputs retrieved\n');

  } catch (error) {
    console.log('⚠️  CloudFormation stack not found. Deploy backend first:\n   cd backend && sam deploy --guided\n');
  }

  try {
    // 2. Get Cognito User Pools
    console.log('[2/5] Fetching Cognito User Pools...');
    const cognitoClient = new CognitoIdentityProviderClient({ region });
    const poolsResponse = await cognitoClient.send(
      new ListUserPoolsCommand({ MaxResults: 10 })
    );
    
    const quickchatPool = poolsResponse.UserPools?.find(
      pool => pool.Name?.toLowerCase().includes('quickchat')
    );
    
    if (quickchatPool) {
      config.VITE_COGNITO_USER_POOL_ID = quickchatPool.Id;
      console.log(`✅ Found User Pool: ${quickchatPool.Name}\n`);

      // 3. Get App Clients
      console.log('[3/5] Fetching Cognito App Clients...');
      const clientsResponse = await cognitoClient.send(
        new ListUserPoolClientsCommand({ 
          UserPoolId: quickchatPool.Id,
          MaxResults: 10 
        })
      );
      
      if (clientsResponse.UserPoolClients?.[0]) {
        config.VITE_COGNITO_CLIENT_ID = clientsResponse.UserPoolClients[0].ClientId;
        console.log('✅ App Client retrieved\n');
      }
    } else {
      console.log('⚠️  No QuickChat Cognito User Pool found\n');
    }

  } catch (error) {
    console.log('⚠️  Error fetching Cognito resources:', error.message, '\n');
  }

  try {
    // 4. Get API Gateway WebSocket (backup if CloudFormation failed)
    if (!config.VITE_WEBSOCKET_URL) {
      console.log('[4/5] Fetching API Gateway WebSocket APIs...');
      const apiClient = new ApiGatewayV2Client({ region });
      const apisResponse = await apiClient.send(new GetApisCommand({}));
      
      const wsApi = apisResponse.Items?.find(
        api => api.ProtocolType === 'WEBSOCKET' && 
               api.Name?.toLowerCase().includes('quickchat')
      );
      
      if (wsApi) {
        config.VITE_WEBSOCKET_URL = `wss://${wsApi.ApiId}.execute-api.${region}.amazonaws.com/prod`;
        console.log('✅ WebSocket API found\n');
      }
    } else {
      console.log('[4/5] WebSocket URL already retrieved from stack\n');
    }

  } catch (error) {
    console.log('⚠️  Error fetching API Gateway:', error.message, '\n');
  }

  try {
    // 5. Get S3 Buckets (backup if CloudFormation failed)
    if (!config.VITE_ATTACHMENTS_BUCKET) {
      console.log('[5/5] Fetching S3 Buckets...');
      const s3Client = new S3Client({ region });
      const bucketsResponse = await s3Client.send(new ListBucketsCommand({}));
      
      const attachmentsBucket = bucketsResponse.Buckets?.find(
        bucket => bucket.Name?.includes('quickchat-attachments')
      );
      
      if (attachmentsBucket) {
        config.VITE_ATTACHMENTS_BUCKET = attachmentsBucket.Name;
        console.log('✅ S3 Bucket found\n');
      }
    } else {
      console.log('[5/5] S3 Bucket already retrieved from stack\n');
    }

  } catch (error) {
    console.log('⚠️  Error fetching S3 buckets:', error.message, '\n');
  }

  // Generate .env file
  console.log('========================================');
  console.log('📝 Configuration Summary:');
  console.log('========================================\n');
  
  let envContent = '# QuickChat Environment Variables\n';
  envContent += '# Auto-generated by fetch-aws-resources.mjs\n\n';
  
  Object.entries(config).forEach(([key, value]) => {
    console.log(`${key}=${value}`);
    envContent += `${key}=${value}\n`;
  });

  const missingKeys = [
    'VITE_COGNITO_USER_POOL_ID',
    'VITE_COGNITO_CLIENT_ID',
    'VITE_WEBSOCKET_URL',
    'VITE_API_URL',
    'VITE_ATTACHMENTS_BUCKET'
  ].filter(key => !config[key]);

  if (missingKeys.length > 0) {
    console.log('\n⚠️  Missing configuration:');
    missingKeys.forEach(key => {
      console.log(`   - ${key}`);
      envContent += `${key}=\n`;
    });
    console.log('\nPlease complete the setup:');
    if (missingKeys.includes('VITE_WEBSOCKET_URL')) {
      console.log('   1. Deploy backend: cd backend && sam deploy --guided');
    }
    if (missingKeys.includes('VITE_COGNITO_USER_POOL_ID')) {
      console.log('   2. Create Cognito User Pool in AWS Console');
    }
  }

  // Write to .env file
  const envPath = join(process.cwd(), 'frontend', '.env');
  writeFileSync(envPath, envContent);
  console.log(`\n✅ Configuration saved to: ${envPath}`);
  console.log('\n🚀 Next: cd frontend && npm run dev\n');
}

fetchAWSResources().catch(console.error);
